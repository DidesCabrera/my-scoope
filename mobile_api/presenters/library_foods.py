def food_picker_item_payload(item):
    return {
        "id": item.id,
        "name": item.name,
        "display_name": item.display_name,
        "protein": item.protein,
        "carbs": item.carbs,
        "fat": item.fat,
        "total_kcal": item.total_kcal,
        "protein_allocation": item.alloc.get("protein", 0),
        "carbs_allocation": item.alloc.get("carbs", 0),
        "fat_allocation": item.alloc.get("fat", 0),
        "source": item.source,
        "is_user_food": item.is_user_food,
        "is_verified": item.is_verified,
        "data_quality_score": item.data_quality_score,
        "quantity_unit": item.quantity_unit,
        "default_portion": item.default_portion,
        "household_amount": item.household_amount,
        "household_measure": item.household_measure,
        "household_measure_label": item.household_measure_label,
        "household_detail": item.household_detail,
        "myscoope_group": item.myscoope_group,
        "myscoope_group_label": item.myscoope_group_label,
        "emoji": item.emoji,
        "visual_key": item.visual_key,
    }
